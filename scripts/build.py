"""Build everything that is generated from the schema and the concepts.

The schema (schema/) and the concepts (data/) are the only sources. This script writes:

- generated/json_schema/: JSON Schema of the model, for validating instance files anywhere.
- generated/owl/: the schema as OWL, in Turtle.
- generated/python/: Pydantic classes, for code that reads or writes the model.
- generated/skos/concepts.ttl: the concepts as a SKOS concept scheme, labels tagged with
  their language.
- docs/glossary.md: the glossary, one entry per concept.

Usage:
  uv run python scripts/build.py           # write the files
  uv run python scripts/build.py --check   # fail if a committed file is not what the sources give
"""

from __future__ import annotations

import argparse
import difflib
import subprocess
import sys
import tempfile
from pathlib import Path

import yaml
from rdflib import RDF, Graph, Literal, Namespace, URIRef
from rdflib.namespace import DCTERMS, SKOS

ROOT = Path(__file__).resolve().parent.parent
SCHEMA = ROOT / "schema" / "protein_function_prediction_semantic_model.yaml"
CONCEPTS = ROOT / "data" / "concepts.yaml"
BASE = "https://w3id.org/protein-function-prediction-semantic-model/"
MODEL = Namespace(BASE)

# (output path relative to the root, LinkML generator and its arguments)
GENERATORS: list[tuple[str, list[str]]] = [
    ("generated/json_schema/protein_function_prediction_semantic_model.schema.json",
     ["gen-json-schema", "--top-class", "SemanticModel"]),
    ("generated/owl/protein_function_prediction_semantic_model.owl.ttl",
     ["gen-owl", "--no-metadata"]),
    ("generated/python/protein_function_prediction_semantic_model.py",
     ["gen-pydantic", "--no-metadata"]),
]


def run_generator(command: list[str]) -> str:
    """Run one LinkML generator on the schema and return what it prints.

    The schema is passed relative to the root, from the root, because some generators
    copy the path they were given into their output; an absolute path would make the
    output depend on where the repository was cloned.
    """
    relative = SCHEMA.relative_to(ROOT).as_posix()
    done = subprocess.run([*command, relative], capture_output=True, text=True, check=False, cwd=ROOT)
    if done.returncode != 0:
        sys.exit(f"{command[0]} failed:\n{done.stderr}")
    return done.stdout


def skos_turtle(model: dict) -> str:
    """The concepts as a SKOS concept scheme, with language-tagged labels."""
    g = Graph()
    g.bind("skos", SKOS)
    g.bind("dcterms", DCTERMS)
    g.bind("protein_function_prediction", MODEL)
    scheme = URIRef(BASE + model["id"])
    g.add((scheme, RDF.type, SKOS.ConceptScheme))
    g.add((scheme, DCTERMS.title, Literal(model["title"], lang="en")))
    g.add((scheme, DCTERMS.hasVersion, Literal(model["version"])))
    for c in model["concepts"]:
        node = URIRef(BASE + c["id"])
        g.add((node, RDF.type, SKOS.Concept))
        g.add((node, SKOS.inScheme, scheme))
        g.add((scheme, SKOS.hasTopConcept, node))
        g.add((node, SKOS.prefLabel, Literal(c["label_en"], lang="en")))
        g.add((node, SKOS.prefLabel, Literal(c["label_es"], lang="es")))
        g.add((node, SKOS.definition, Literal(c["definition_en"], lang="en")))
        for name in c.get("candidate_names", []):
            if name != c["label_en"]:
                g.add((node, SKOS.altLabel, Literal(name, lang="en")))
        for name in c.get("deprecated_names", []):
            g.add((node, SKOS.hiddenLabel, Literal(name)))
        for example in c.get("examples", []):
            g.add((node, SKOS.example, Literal(example)))
        if "external_match" in c:
            g.add((node, MODEL.external_match, Literal(c["external_match"])))
        g.add((node, MODEL.status, Literal(c["status"])))
        g.add((node, MODEL.top_category, Literal(c["top_category"])))
    return g.serialize(format="turtle")


def glossary(model: dict) -> str:
    """The glossary in Markdown, sorted by English label."""
    lines = [
        f"# Glossary of the {model['title'][0].lower() + model['title'][1:]}",
        "",
        f"Version {model['version']}. Generated by `scripts/build.py` from `data/concepts.yaml`; do not edit by hand.",
        "",
    ]
    if any(c["status"] == "candidate" for c in model["concepts"]):
        lines += [
            "Every name below is a candidate: none is accepted yet. A row with several candidate names "
            "groups concepts that still have to be split.",
            "",
        ]
    for c in sorted(model["concepts"], key=lambda c: c["label_en"].lower()):
        lines += [f"## {c['label_en']}", ""]
        lines.append(f"- **Identifier:** `{c['id']}` ({c['status']})")
        lines.append(f"- **Spanish label:** {c['label_es']}")
        if len(c["candidate_names"]) > 1 or c["candidate_names"][0] != c["label_en"]:
            lines.append("- **Candidate names:** " + "; ".join(c["candidate_names"]))
        lines.append(f"- **Top category:** {c['top_category'].replace('_', ' ')}")
        if c.get("values"):
            lines.append("- **Values:** " + ", ".join(f"`{v}`" for v in c["values"]))
        if c.get("examples"):
            lines.append("- **Examples:** " + "; ".join(c["examples"]))
        if c.get("external_match"):
            lines.append(f"- **Outside the project:** {c['external_match']}")
        lines += ["", c["definition_en"], ""]
        uses = "; ".join(f"{u['where']}: {', '.join(u['names'])}" for u in c.get("current_names", []))
        if uses:
            lines += [f"Names today: {uses}.", ""]
    return "\n".join(lines)


def build() -> dict[str, str]:
    """Every generated file, by path relative to the root."""
    model = yaml.safe_load(CONCEPTS.read_text(encoding="utf-8"))
    out = {path: run_generator(cmd) for path, cmd in GENERATORS}
    out["generated/skos/concepts.ttl"] = skos_turtle(model)
    out["docs/glossary.md"] = glossary(model)
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="compare with the committed files instead of writing")
    args = parser.parse_args(argv)
    files = build()
    stale = []
    for rel, text in files.items():
        path = ROOT / rel
        if args.check:
            current = path.read_text(encoding="utf-8") if path.exists() else ""
            if current != text:
                stale.append(rel)
                sys.stdout.writelines(difflib.unified_diff(
                    current.splitlines(keepends=True), text.splitlines(keepends=True), rel, rel + " (built)", n=1))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    if stale:
        print(f"\n{len(stale)} generated file(s) out of date: run uv run python scripts/build.py", file=sys.stderr)
        return 1
    print("checked" if args.check else "built", len(files), "files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
